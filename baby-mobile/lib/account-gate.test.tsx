import React from "react";
import { act, create, type ReactTestRenderer } from "react-test-renderer";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { emptyState } from "./models";
const f = vi.hoisted(() => ({ account: null as any, alert: vi.fn(), waiting: 0 }));
vi.mock("@/lib/waiting-shares", () => ({ waitingShareCount: async () => f.waiting, removedWarning: () => "Waiting shares will be removed.", confirmSignOut: vi.fn() }));
vi.mock("react-native", () => ({ Alert: { alert: f.alert } }));
vi.mock("@/lib/context", () => ({ useBaby: () => f.account }));
vi.mock("@/lib/share-session-state", () => ({ revokeShareSession: vi.fn() }));
vi.mock("../components/ui", () => ({ Button: "Button", Empty: "Empty", Loading: "Loading", Notice: "Notice", Screen: "Screen" }));
vi.mock("@/lib/account-deletion", () => ({ confirmAccountDeletion: vi.fn() }));
vi.mock("@/lib/models", () => import("./models"));
vi.mock("@/lib/outbox", () => import("./outbox"));
import { AccountGate } from "../components/account-gate";
let view: ReactTestRenderer;
beforeEach(() => { vi.stubGlobal("React", React); vi.stubGlobal("IS_REACT_ACT_ENVIRONMENT", true); f.alert.mockReset(); f.waiting = 0; });
afterEach(async () => { if (view) await act(async () => view.unmount()); vi.unstubAllGlobals(); });
it.each(["raw read error", "queued work", "held work", "waiting share", "unreadable share count"])("warns before clearing %s from the account gate", async (kind) => {
  f.account = { ready: false, error: kind === "raw read error" ? "Unexpected end of JSON input" : "", state: emptyState(), signOut: vi.fn() };
  if (kind === "waiting share") f.waiting = 1;
  if (kind === "unreadable share count") f.waiting = -1;
  if (kind === "queued work") f.account.state.outbox = [{ id: "real-save" }];
  if (kind === "held work") f.account.state.heldDrafts = [{ id: "unfinished" }];
  await act(async () => { view = create(<AccountGate><>opened</></AccountGate>); });
  await act(async () => { await view.root.findAll((n) => n.type === "Button" as any).find((n) => n.props.title === "Sign out")!.props.onPress(); });
  expect(f.account.signOut).not.toHaveBeenCalled();
  const buttons = f.alert.mock.calls[0][2];
  expect(f.alert.mock.calls[0][1]).toContain("removes them");
  buttons.find((b: any) => b.style === "cancel").onPress?.();
  expect(f.account.signOut).not.toHaveBeenCalled();
  buttons.find((b: any) => b.style === "destructive").onPress();
  expect(f.account.signOut).toHaveBeenCalledOnce();
});
